classdef IcaRemovalStage
    %ICAREMOVALSTAGE Passive Pz readout directly AFTER original IC deletion.
    % Never changes EEG, trial eligibility, ICA class decisions or Rank.
    methods (Static)
        function out = capturePost(EEG,contract)
            out=struct('status','unavailable','reason','', ...
                'sourceStage','immediately-after-icremove', ...
                'eventIds',[],'conditionIndex',[], ...
                'observedPzUv',[],'nEvents',NaN,'srate',NaN, ...
                'channel','Pz','metric','raw Pz eventwise baseline-corrected 300-600ms mean (uV)');
            assert(isstruct(EEG) && isa(contract,'pipecompare.eval.Contract') && ...
                strcmp(contract.analysis,'erp') && numel(contract.conditions)==2 && ...
                numel(contract.components)==1 && ...
                strcmpi(contract.components(1).name,'P3') && ...
                numel(contract.baseline)==2, 'PipeCompare:IcaRemovalStage', ...
                'Expected an original two-condition P3 ERP source contract.');
            assert(isfield(EEG,'data') && EEG.nbchan==numel(EEG.chanlocs) && ...
                EEG.srate>0,'PipeCompare:IcaRemovalStage', ...
                'Incomplete EEG channel geometry.');
            labels={EEG.chanlocs.labels};
            at=find(strcmpi(labels,'Pz'));
            assert(numel(at)==1,'PipeCompare:IcaRemovalStage', ...
                'No unique Pz sensor in the actual after-removal EEG.');
            Q=EEG; % Value semantics / copy-on-write: original pipeline never changed.
            if Q.trials==1 && (~isfield(Q,'epoch') || isempty(Q.epoch))
                [Q,~,~]=pop_epoch(Q,contract.allEvents(),contract.epoch,'epochinfo','yes');
            end
            T=pipecompare.eval.Measure.trials(Q,contract,true);
            ids=double(T.id(:)');
            cond=double(T.cond(:)');
            ep=double(T.epoch(:)');
            assert(numel(ids)>=2 && numel(unique(ids))==numel(ids) && ...
                numel(cond)==numel(ids) && numel(ep)==numel(ids) && ...
                all(ismember(cond,[1 2])) && all(ismember([1 2],cond)), ...
                'PipeCompare:IcaRemovalStage','Unverified/duplicated event source identities.');
            times=double(Q.xmin)+(0:Q.pnts-1)/double(Q.srate);
            base=times>=contract.baseline(1)-1e-9 & ...
                 times<=contract.baseline(2)+1e-9;
            win=times>=contract.components(1).window(1)-1e-9 & ...
                times<=contract.components(1).window(2)+1e-9;
            assert(nnz(base)>=2 && nnz(win)>=2, ...
                'PipeCompare:IcaRemovalStage','Pz ERP window or baseline missing.');
            x=reshape(double(Q.data(at,:,ep)),Q.pnts,[]);
            assert(size(x,2)==numel(ids) && all(isfinite(x(:))), ...
                'PipeCompare:IcaRemovalStage','Nonfinite or misaligned real sensor epochs.');
            value=mean(x(win,:),1)-mean(x(base,:),1);
            assert(all(isfinite(value)), 'PipeCompare:IcaRemovalStage', ...
                'Unable to compute real post-removal P300 sensor amplitude.');
            out.status='complete';
            out.eventIds=ids;
            out.conditionIndex=cond;
            out.observedPzUv=value;
            out.nEvents=numel(ids);
            out.srate=double(Q.srate);
        end
    end
end
