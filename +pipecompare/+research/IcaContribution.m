classdef IcaContribution
    %ICACONTRIBUTION Read-only Pz component event signatures before pop_subcomp.
    % No algorithm/recommendation change and NOT a final-ERP causal estimate.
    methods (Static)
        function out = capturePreRemove(EEG,contract)
            out = struct('status','unavailable','reason','', ...
                'sourceStage','immediately-before-icremove', ...
                'componentUv',[],'eventIds',[],'conditionIndex',[], ...
                'observedPzUv',[],'residualPzUv',[],'maxAbsResidualUv',NaN, ...
                'relativeResidualRMS',NaN,'rank',NaN,'nComponents',NaN, ...
                'nICAChannels',NaN,'nEvents',NaN,'srate',NaN);
            assert(isstruct(EEG) && isstruct(contract) == false, ...
                'PipeCompare:IcaContribution','Need original EEG and Contract object.');
            assert(strcmp(contract.analysis,'erp') && numel(contract.conditions)==2 && ...
                numel(contract.components)==1 && ...
                strcmpi(contract.components(1).name,'P3') && ...
                ~isempty(contract.baseline) && ...
                numel(contract.baseline)==2, ...
                'PipeCompare:IcaContribution','Only two-condition P3 ERP with baseline.');
            assert(isfield(EEG,'icaweights') && isfield(EEG,'icasphere') && ...
                ~isempty(EEG.icaweights) && ~isempty(EEG.icasphere) && ...
                isfield(EEG,'icachansind') && ~isempty(EEG.icachansind), ...
                'PipeCompare:IcaContribution','Pre-removal ICA decomposition missing.');
            ix=double(EEG.icachansind(:)');
            assert(all(isfinite(ix)) && all(ix>=1) && all(ix<=EEG.nbchan) && ...
                all(ix==fix(ix)) && numel(unique(ix))==numel(ix), ...
                'PipeCompare:IcaContribution','ICA channel indexing invalid.');
            W=double(EEG.icaweights)*double(EEG.icasphere);
            assert(size(W,2)==numel(ix) && all(isfinite(W(:))) && ...
                size(W,1)>0,'PipeCompare:IcaContribution', ...
                'ICA unmixing dimensions or values invalid.');
            mixing=pinv(W);
            assert(all(isfinite(mixing(:))), ...
                'PipeCompare:IcaContribution','ICA inverse mixing map not finite.');
            labels={EEG.chanlocs.labels};
            pz=find(strcmpi(labels,'Pz'));
            assert(numel(pz)==1 && ismember(pz,ix), ...
                'PipeCompare:IcaContribution','Pz absent from ICA montage.');
            pzInICA=find(ix==pz,1);
            Q=EEG; % copy-on-write, do not modify the real search's EEG.
            if Q.trials==1 && (~isfield(Q,'epoch') || isempty(Q.epoch))
                [Q,~,~]=pop_epoch(Q,contract.allEvents(),contract.epoch, ...
                    'epochinfo','yes');
            end
            T=pipecompare.eval.Measure.trials(Q,contract,true);
            ids=double(T.id(:)');
            cond=double(T.cond(:)');
            ep=double(T.epoch(:)');
            assert(numel(ids)>=2 && numel(ids)==numel(unique(ids)) && ...
                numel(ids)==numel(cond) && numel(ids)==numel(ep) && ...
                all(ismember(cond,[1 2])), ...
                'PipeCompare:IcaContribution','Ambiguous trial/condition urevents.');
            times=double(Q.xmin)+(0:Q.pnts-1)/double(Q.srate);
            base=times>=contract.baseline(1)-1e-9 & ...
                 times<=contract.baseline(2)+1e-9;
            p3=times>=contract.components(1).window(1)-1e-9 & ...
                times<=contract.components(1).window(2)+1e-9;
            assert(nnz(base)>=2 && nnz(p3)>=2, ...
                'PipeCompare:IcaContribution','Baseline/P300 time samples unavailable.');
            n=numel(ids);nIca=size(W,1);
            X=reshape(double(Q.data(ix,:,ep)),numel(ix),[]);
            assert(all(isfinite(X(:))),'PipeCompare:IcaContribution', ...
                'Nonfinite source signal at evaluated events.');
            activation=reshape(W*X,nIca,Q.pnts,n);
            avgP3=reshape(mean(activation(:,p3,:),2),nIca,n);
            avgBase=reshape(mean(activation(:,base,:),2),nIca,n);
            % Each component is a *stage-specific*, raw Pz projected signal.
            % Normalization is not applied: mixing*activations remains in uV.
            contribution=mixing(pzInICA,:)' .* (avgP3-avgBase);
            observed=reshape(double(Q.data(pz,:,ep)),Q.pnts,n);
            observed=mean(observed(p3,:),1)-mean(observed(base,:),1);
            residual=observed-sum(contribution,1);
            assert(all(isfinite(contribution(:))) && all(isfinite(residual)), ...
                'PipeCompare:IcaContribution','Component signature nonfinite.');
            out.status='complete';
            out.eventIds=ids;
            out.conditionIndex=cond;
            out.componentUv=contribution;
            out.observedPzUv=observed;
            out.residualPzUv=residual;
            out.maxAbsResidualUv=max(abs(residual));
            out.relativeResidualRMS=sqrt(mean(residual.^2))/ ...
                max(sqrt(mean(observed.^2)),eps);
            out.rank=rank(W);
            out.nComponents=nIca;
            out.nICAChannels=numel(ix);
            out.nEvents=n;
            out.srate=double(Q.srate);
        end
    end
end
